CREATE TABLE store_purchase_requests (
    purchase_request_id uuid PRIMARY KEY,
    account_id uuid NOT NULL,
    request_bytes bytea NOT NULL CHECK (octet_length(request_bytes) BETWEEN 1 AND 1024),
    request_digest text NOT NULL CHECK (request_digest ~ '^[0-9a-f]{64}$'),
    result text NOT NULL CHECK (result IN ('ACCEPTED','INSUFFICIENT_BALANCE','STALE_QUOTE','OFFER_UNAVAILABLE','ACCOUNT_RESTRICTED','PURCHASE_DISABLED')),
    answer_bytes bytea NOT NULL CHECK (octet_length(answer_bytes) BETWEEN 1 AND 2048),
    decided_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE store_orders (
    order_id uuid PRIMARY KEY,
    purchase_request_id uuid NOT NULL UNIQUE REFERENCES store_purchase_requests,
    account_id uuid NOT NULL,
    character_id uuid NOT NULL,
    world_id uuid NOT NULL,
    wallet_operation_id uuid NOT NULL UNIQUE REFERENCES wallet_operations,
    wallet_idempotency_key text NOT NULL UNIQUE,
    currency text NOT NULL CHECK (currency='COINS'),
    total_price bigint NOT NULL CHECK (total_price>0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE store_order_lines (
    line_id uuid PRIMARY KEY,
    order_id uuid NOT NULL UNIQUE REFERENCES store_orders,
    catalog_revision text NOT NULL,
    offer_key text NOT NULL,
    quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 100),
    unit_price bigint NOT NULL CHECK (unit_price>0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (catalog_revision,offer_key) REFERENCES store_offers
);
CREATE TABLE store_fulfilment_units (
    entitlement_id uuid PRIMARY KEY,
    line_id uuid NOT NULL REFERENCES store_order_lines,
    unit_index integer NOT NULL CHECK (unit_index BETWEEN 0 AND 7),
    account_id uuid NOT NULL,
    product_id text NOT NULL,
    product_version text NOT NULL,
    unit_kind text NOT NULL CHECK (unit_kind IN ('PREMIUM_TIME','COSMETIC','ITEM')),
    grant_key text NOT NULL,
    grant_revision text NOT NULL,
    quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 65535),
    state text NOT NULL DEFAULT 'DELIVERY_PENDING' CHECK (state IN ('DELIVERY_PENDING','DELIVERED','CLAIM_PENDING','CLAIMED','REVOKED','RECLAIMED','MANUAL_REVIEW','REVERSAL_PARTIAL')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(line_id,unit_index)
);
CREATE INDEX store_fulfilment_account_state ON store_fulfilment_units(account_id,state);
CREATE TABLE store_operations (
    source_revision bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    operation_id uuid PRIMARY KEY,
    issuer_authority text NOT NULL CHECK (issuer_authority='OTERYN_PLATFORM_STORE_AUTHORITY'),
    operation_kind text NOT NULL CHECK (operation_kind IN ('DELIVER','CLAIM','REVOKE_UNCLAIMED','RECLAIM','FLAG')),
    entitlement_id uuid NOT NULL REFERENCES store_fulfilment_units,
    intent_bytes bytea NOT NULL CHECK (octet_length(intent_bytes) BETWEEN 1 AND 4096),
    binding_digest text NOT NULL CHECK (binding_digest ~ '^[0-9a-f]{64}$'),
    state text NOT NULL DEFAULT 'PENDING' CHECK (state IN ('PENDING','REOPENED','COMMITTED','REJECTED')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX store_operations_pending ON store_operations(operation_kind,state,source_revision,operation_id);
-- Rate budgets are shared across processes and bounded to one row per account/scope.
CREATE TABLE store_wire_limits (
    scope text NOT NULL CHECK (scope IN ('purchase','read','peer')),
    subject text NOT NULL,
    window_start timestamptz NOT NULL DEFAULT now(),
    attempts integer NOT NULL CHECK (attempts>0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY(scope,subject)
);
CREATE TRIGGER store_purchase_answer_immutable BEFORE UPDATE OR DELETE OR TRUNCATE
    ON store_purchase_requests FOR EACH STATEMENT EXECUTE FUNCTION wallet_reject_rewrite();
CREATE TRIGGER store_orders_immutable BEFORE UPDATE OR DELETE OR TRUNCATE
    ON store_orders FOR EACH STATEMENT EXECUTE FUNCTION wallet_reject_rewrite();
CREATE TRIGGER store_order_lines_immutable BEFORE UPDATE OR DELETE OR TRUNCATE
    ON store_order_lines FOR EACH STATEMENT EXECUTE FUNCTION wallet_reject_rewrite();
-- Delivery can advance state, but the sold unit and signed intent binding never change.
CREATE TRIGGER store_fulfilment_binding_immutable BEFORE UPDATE OF
    entitlement_id,line_id,unit_index,account_id,product_id,product_version,unit_kind,grant_key,grant_revision,quantity
    ON store_fulfilment_units FOR EACH STATEMENT EXECUTE FUNCTION wallet_reject_rewrite();
CREATE TRIGGER store_operations_binding_immutable BEFORE UPDATE OF
    source_revision,operation_id,issuer_authority,operation_kind,entitlement_id,intent_bytes,binding_digest
    ON store_operations FOR EACH STATEMENT EXECUTE FUNCTION wallet_reject_rewrite();
CREATE TRIGGER store_operations_no_delete BEFORE DELETE OR TRUNCATE
    ON store_operations FOR EACH STATEMENT EXECUTE FUNCTION wallet_reject_rewrite();
